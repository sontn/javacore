package StudyAndShare;

public class Switch {
    public static void main(String[] args) {
        int day = 3;
        switch (day) {
            case 1: System.out.println("Hom nay la ngay thu 2"); break;
            case 2:
                System.out.println("Hom nay la ngay thu 3"); break;
            default:
                System.out.println("Khong co ngay nao ca"); break;
        }
        System.out.println("This is a test");
    }
}
